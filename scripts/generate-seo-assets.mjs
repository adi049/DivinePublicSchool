#!/usr/bin/env node
// ============================================================================
// SEO ASSET GENERATOR
// ============================================================================
// Emits everything search engines need that a hash-routed SPA cannot provide
// on its own:
//
//   public/robots.txt          crawl directives + sitemap pointer
//   public/sitemap.xml         XML sitemap of the crawlable URLs
//   public/404.html            GitHub Pages 404 → bounces into the SPA
//   public/site.webmanifest    PWA/icon metadata
//   dist/<slug>/index.html     one real, crawlable entry page per route
//
// WHY THE ENTRY PAGES EXIST
// -------------------------
// The site must keep HashRouter for GitHub Pages, but search engines ignore
// everything after '#', so `…/#/about` is not a separately indexable URL.
// Each generated entry page is a genuine URL (…/DivinePublicSchool/about/)
// carrying its own title, description, canonical, Open Graph, Twitter card
// and JSON-LD. It then boots the normal app bundle and sets the hash so the
// visitor lands on the right screen — no redirect, no interstitial, no
// duplicate content (every entry page self-canonicalises).
//
// Run automatically by `npm run build` (after `vite build`).
// ============================================================================

import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  SITE_URL,
  ORG,
  PAGES,
  canonicalFor,
  absUrl,
  schemaGraphFor,
} from '../src/data/seo.js'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC_DIR = join(ROOT, 'public')
const DIST_DIR = join(ROOT, 'dist')
const HAS_DIST = existsSync(join(DIST_DIR, 'index.html'))
const BASE_PATH = new URL(SITE_URL).pathname // '/DivinePublicSchool/'
const TODAY = new Date().toISOString().slice(0, 10)

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

/** Write to public/, and mirror into dist/ when a build is present. */
function writeBoth(relPath, content) {
  for (const base of HAS_DIST ? [PUBLIC_DIR, DIST_DIR] : [PUBLIC_DIR]) {
    const target = join(base, relPath)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, content)
  }
  console.log(`  ✓ ${relPath}`)
}

// ---------------------------------------------------------------------------
// 1. robots.txt
// ---------------------------------------------------------------------------
function robotsTxt() {
  return `# robots.txt — ${ORG.name}
# NOTE: on a GitHub Pages *project* site, crawlers read robots.txt from the
# domain root (https://adi049.github.io/robots.txt), not from this sub-path.
# This file becomes authoritative the moment the site moves to a custom domain.

User-agent: *
Allow: ${BASE_PATH}

# Admin screens are hash routes (…/#/admin) and are not crawlable, but they are
# also marked noindex in the app itself.
Disallow: ${BASE_PATH}admin

Sitemap: ${SITE_URL}sitemap.xml
`
}

// ---------------------------------------------------------------------------
// 2. sitemap.xml
// ---------------------------------------------------------------------------
function sitemapXml() {
  const urls = PAGES.map((page) => {
    const loc = canonicalFor(page)
    const priority = page.slug === '' ? '1.0' : ['admissions', 'about', 'contact'].includes(page.key) ? '0.9' : '0.8'
    const freq = ['timetable', 'date-sheets', 'gallery'].includes(page.key) ? 'weekly' : 'monthly'
    return `  <url>
    <loc>${esc(loc)}</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${priority}</priority>
    <image:image>
      <image:loc>${esc(absUrl(page.image))}</image:loc>
      <image:title>${esc(page.heading)} — ${esc(ORG.name)}</image:title>
    </image:image>
  </url>`
  }).join('\n')

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Sitemap for ${ORG.name} — generated by scripts/generate-seo-assets.mjs -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls}
</urlset>
`
}

// ---------------------------------------------------------------------------
// 3. site.webmanifest
// ---------------------------------------------------------------------------
function webManifest() {
  return JSON.stringify(
    {
      name: ORG.name,
      short_name: 'Divine Public School',
      description: `${ORG.board} school in ${ORG.locality}, ${ORG.region} — Nursery to Class XII.`,
      start_url: BASE_PATH,
      scope: BASE_PATH,
      display: 'standalone',
      background_color: '#ffffff',
      theme_color: '#12295c',
      lang: 'en-IN',
      icons: [
        { src: `${BASE_PATH}favicon.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
      ],
    },
    null,
    2,
  )
}

// ---------------------------------------------------------------------------
// 4. 404.html — GitHub Pages serves this for unknown paths
// ---------------------------------------------------------------------------
function notFoundHtml() {
  return `<!doctype html>
<html lang="en-IN">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>Page Not Found (404) | ${esc(ORG.name)}</title>
    <meta name="description" content="The page you requested could not be found on the ${esc(ORG.name)} website." />
    <meta name="robots" content="noindex, follow" />
    <link rel="icon" type="image/png" href="${BASE_PATH}favicon.png" />
    <style>
      body{margin:0;min-height:100vh;display:grid;place-items:center;background:#f6f9fd;
        font-family:Inter,system-ui,-apple-system,"Segoe UI",sans-serif;color:#12295c;padding:1.5rem}
      .box{max-width:34rem;text-align:center}
      h1{font-size:clamp(1.5rem,4vw,2.1rem);margin:0 0 .6rem}
      p{color:#4a5a7a;line-height:1.65;margin:0 0 1.4rem}
      a.btn{display:inline-block;background:#12295c;color:#fff;text-decoration:none;
        padding:.8rem 1.5rem;border-radius:999px;font-weight:600}
    </style>
    <script>
      // Known deep paths bounce into the matching hash route of the SPA.
      (function () {
        var base = '${BASE_PATH}'
        var path = location.pathname.indexOf(base) === 0 ? location.pathname.slice(base.length) : ''
        var slug = path.replace(/^\\/+|\\/+$/g, '').split('/')[0]
        var known = ${JSON.stringify(PAGES.filter((p) => p.slug).map((p) => p.slug))}
        var routes = ${JSON.stringify(
          Object.fromEntries(PAGES.filter((p) => p.slug).map((p) => [p.slug, p.route])),
        )}
        if (slug && known.indexOf(slug) !== -1) location.replace(base + '#' + routes[slug])
      })()
    </script>
  </head>
  <body>
    <div class="box">
      <h1>This page could not be found</h1>
      <p>
        The address you entered does not exist on the ${esc(ORG.name)} website.
        It may have been moved, or the link may be incomplete.
      </p>
      <a class="btn" href="${BASE_PATH}">Go to the homepage</a>
    </div>
  </body>
</html>
`
}

// ---------------------------------------------------------------------------
// 5. Per-route crawlable entry pages (needs the built asset filenames)
// ---------------------------------------------------------------------------

/** Pull the hashed <script>/<link> asset tags out of the built index.html. */
function readBuiltAssetTags() {
  const html = readFileSync(join(DIST_DIR, 'index.html'), 'utf8')
  const tags = [
    ...(html.match(/<script[^>]*type="module"[^>]*><\/script>/g) || []),
    ...(html.match(/<link[^>]*rel="(?:stylesheet|modulepreload)"[^>]*>/g) || []),
  ]
  if (!tags.length) throw new Error('No built asset tags found in dist/index.html')
  return tags.join('\n    ')
}

/** Readable no-JS / scraper fallback: real content, no hidden text. */
function fallbackMarkup(page) {
  const links = PAGES.filter((p) => p.key !== page.key)
    .map((p) => `<li><a href="${canonicalFor(p)}">${esc(p.heading)}</a></li>`)
    .join('\n          ')
  return `<h1>${esc(page.heading)}</h1>
        <p><strong>${esc(ORG.name)}</strong> — ${esc(ORG.board)} curriculum, ${esc(ORG.addressFull)}</p>
        <p>${esc(page.intro)}</p>
        <p>
          Telephone: <a href="tel:${ORG.phones[0].replace(/[^+\d]/g, '')}">${esc(ORG.phones[0])}</a> ·
          <a href="tel:${ORG.phones[1].replace(/[^+\d]/g, '')}">${esc(ORG.phones[1])}</a><br />
          Email: <a href="mailto:${ORG.email}">${esc(ORG.email)}</a><br />
          <a href="${esc(ORG.mapsUrl)}" rel="noopener">View the school location on Google Maps</a>
        </p>
        <p>This website needs JavaScript for its full experience. Other pages:</p>
        <ul>
          ${links}
        </ul>`
}

function entryPageHtml(page, assetTags) {
  const canonical = canonicalFor(page)
  const image = absUrl(page.image)
  const graph = schemaGraphFor(page)
  return `<!doctype html>
<html lang="en-IN">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />

    <title>${esc(page.title)}</title>
    <meta name="description" content="${esc(page.description)}" />
    <meta name="keywords" content="${esc((page.keywords || []).join(', '))}" />
    <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1" />
    <meta name="theme-color" content="#12295c" />
    <link rel="canonical" href="${esc(canonical)}" />

    <meta name="geo.region" content="IN-HR" />
    <meta name="geo.placename" content="Gurugram, Haryana" />

    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="${esc(ORG.name)}" />
    <meta property="og:locale" content="en_IN" />
    <meta property="og:title" content="${esc(page.title)}" />
    <meta property="og:description" content="${esc(page.description)}" />
    <meta property="og:url" content="${esc(canonical)}" />
    <meta property="og:image" content="${esc(image)}" />
    <meta property="og:image:alt" content="${esc(page.heading)} — ${esc(ORG.name)}" />

    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${esc(page.title)}" />
    <meta name="twitter:description" content="${esc(page.description)}" />
    <meta name="twitter:image" content="${esc(image)}" />

    <link rel="icon" type="image/png" href="${BASE_PATH}favicon.png" />
    <link rel="apple-touch-icon" href="${BASE_PATH}favicon.png" />
    <link rel="manifest" href="${BASE_PATH}site.webmanifest" />

    <script type="application/ld+json">
${JSON.stringify(graph, null, 2)}
    </script>

    <script>
      // Point the hash router at this page before the app boots. Changing the
      // fragment of the current document is not a redirect, so this URL stays
      // the indexable, canonical one.
      if (!window.location.hash) window.location.hash = '#${page.route}'
    </script>
    ${assetTags}
  </head>
  <body>
    <div id="root"></div>
    <noscript>
      <div style="max-width:46rem;margin:0 auto;padding:2rem 1.25rem;font-family:Inter,system-ui,sans-serif;color:#12295c;line-height:1.65">
        ${fallbackMarkup(page)}
      </div>
    </noscript>
  </body>
</html>
`
}

// ---------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------
console.log('\nSEO assets → ' + SITE_URL)

writeBoth('robots.txt', robotsTxt())
writeBoth('sitemap.xml', sitemapXml())
writeBoth('site.webmanifest', webManifest())
writeBoth('404.html', notFoundHtml())

/**
 * Keep dist/index.html's head in exact sync with the `home` record, so the
 * source index.html can never silently drift away from src/data/seo.js.
 */
function syncHomeHead() {
  const home = PAGES[0]
  const file = join(DIST_DIR, 'index.html')
  let html = readFileSync(file, 'utf8')
  const swap = (re, value) => {
    html = html.replace(re, (m, a, b) => a + value + b)
  }
  html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(home.title)}</title>`)
  swap(/(name="description"\s*\n?\s*content=")[\s\S]*?(")/, esc(home.description))
  swap(/(property="og:title" content=")[^"]*(")/, esc(home.title))
  swap(/(name="twitter:title"\s*\n?\s*content=")[\s\S]*?(")/, esc(home.title))
  swap(/(property="og:description"\s*\n?\s*content=")[\s\S]*?(")/, esc(home.description))
  swap(/(name="twitter:description"\s*\n?\s*content=")[\s\S]*?(")/, esc(home.description))
  swap(/(name="keywords"\s*\n?\s*content=")[\s\S]*?(")/, esc((home.keywords || []).join(', ')))
  writeFileSync(file, html)
  console.log('  ✓ dist/index.html head synced with the home SEO record')
}

if (HAS_DIST) {
  syncHomeHead()
  const assetTags = readBuiltAssetTags()
  for (const page of PAGES) {
    if (!page.slug) continue // home is dist/index.html itself
    const target = join(DIST_DIR, page.slug, 'index.html')
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, entryPageHtml(page, assetTags))
    console.log(`  ✓ dist/${page.slug}/index.html  →  ${canonicalFor(page)}`)
  }
} else {
  console.log('  • dist/ not built yet — per-route entry pages will be written on `npm run build`.')
}

console.log(`\n${PAGES.length} URLs in sitemap.xml\n`)
